"use strict";
/* =============================================================================
   Builds the complete package: every file in this repository that is part of
   the portfolio, in one downloadable archive.
   -----------------------------------------------------------------------------
   build-package.js makes the small archive (just the website).
   This one makes the full archive: the website, the preview server, the build
   scripts, the PDF generator and the documentation - everything needed to
   rebuild it from scratch.

   What is deliberately left out:
     .git/          history, not source
     .env           credentials
     downloads/_stage   scratch space from the zip step
     node_modules   not present, and nothing here needs it
   ========================================================================== */

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..");
const FOLDER = "Abhijeet-Kumar-Prajapati-Complete-Package";
const STAGE = path.join(ROOT, "downloads", "_stage", FOLDER);
const ZIP = path.join(ROOT, "downloads", FOLDER + ".zip");

const EXCLUDE_DIRS = new Set([
  ".git",
  "node_modules",
  "__pycache__",
  ".vscode",
  ".idea",
  ".github",
]);

const EXCLUDE_FILES = new Set([
  ".env",
  ".env.local",
  ".DS_Store",
  "Thumbs.db",
  "desktop.ini",
  "npm-debug.log",
]);

const EXCLUDE_SUFFIX = [".pyc", ".token", ".log"];

/* Already-built downloads are regenerated by this script, so shipping the old
   copies inside the archive would only bloat it. */
const EXCLUDE_PATHS = new Set([
  path.join("downloads", "_stage"),
  path.join("downloads", "Abhijeet-Kumar-Prajapati-Portfolio.zip"),
  path.join("downloads", "Abhijeet-Kumar-Prajapati-Complete-Package.zip"),
]);

/* Walk the tree and collect everything that survives the filters. */
function collect(dir, rel, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const relPath = rel ? path.join(rel, entry.name) : entry.name;
    const abs = path.join(dir, entry.name);

    if (EXCLUDE_PATHS.has(relPath)) continue;
    if (entry.isDirectory()) {
      if (EXCLUDE_DIRS.has(entry.name)) continue;
      collect(abs, relPath, out);
      continue;
    }
    if (EXCLUDE_FILES.has(entry.name)) continue;
    if (EXCLUDE_SUFFIX.some((s) => entry.name.endsWith(s))) continue;
    /* The PDF and package readmes are generated, but they belong in the
       archive so it is complete the moment it is unpacked. */
    out.push(relPath);
  }
  return out;
}

const files = collect(ROOT, "", []).sort();

if (!files.length) {
  console.error("nothing to package");
  process.exit(1);
}

/* Stage a copy, adding the generated PDF so the archive is self-contained. */
fs.rmSync(path.join(ROOT, "downloads", "_stage"), { recursive: true, force: true });

let copied = 0;
for (const rel of files) {
  const from = path.join(ROOT, rel);
  const to = path.join(STAGE, rel);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
  copied++;
}

/* A small index so the top level of the archive is self-explanatory. */
fs.writeFileSync(
  path.join(STAGE, "START-HERE.txt"),
  [
    "Abhijeet Kumar Prajapati - Complete Package",
    "===========================================",
    "",
    "This archive contains the entire portfolio repository: the website, the",
    "local preview server, the PDF and package generators, and the docs.",
    "",
    "WHAT TO DO NEXT",
    "---------------",
    "1. Install Node.js 18 or newer from https://node.org",
    "2. Open a terminal in this folder",
    "3. Run:      npm run dev",
    "4. Open the address it prints, usually http://127.0.0.1:8123/",
    "",
    "There is nothing to install. package.json lists zero dependencies, and",
    "there is no build step - the site is plain HTML, CSS and JavaScript.",
    "",
    "FOLDER MAP",
    "----------",
    "index.html            the page",
    "serve.js              local preview server",
    "assets/style.css      design system, layout, animations, print styles",
    "assets/app.js         rendering, motion, filtering, command palette",
    "assets/data.js        all content - projects, skills, stats",
    "assets/banner.jpg     the banner graphic",
    "downloads/            generated CV PDF and the website-only archive",
    "automation/           the scripts that build the downloadable files",
    "README.md             profile, with every project documented",
    "SECURITY.md           security policy",
    "PRIVACY.md            what the profile exposes",
    "",
    "REBUILDING THE DOWNLOADS",
    "-----------------------",
    "npm run docs      regenerate the CV and Resume PDFs",
    "npm run package   regenerate the website-only archive",
    "npm run full      regenerate this archive",
    "npm run build     all of them, in order",
    "npm run check     run the static checks over the site",
    "",
    "Made by Abhijeet Kumar Prajapati.",
    "",
  ].join("\n"),
  "utf8"
);
copied++;

fs.rmSync(ZIP, { force: true });
execFileSync(
  "powershell",
  [
    "-NoProfile",
    "-Command",
    `Compress-Archive -Path '${STAGE}' -DestinationPath '${ZIP}' -CompressionLevel Optimal -Force`,
  ],
  { stdio: "inherit" }
);

fs.rmSync(path.join(ROOT, "downloads", "_stage"), { recursive: true, force: true });

/* Read the archive back and confirm it is a real, complete zip. */
const buf = fs.readFileSync(ZIP);
if (buf.readUInt32LE(0) !== 0x04034b50) {
  console.error("not a zip file");
  process.exit(1);
}

const eocd = buf.lastIndexOf(Buffer.from([0x50, 0x4b, 0x05, 0x06]));
const total = buf.readUInt16LE(eocd + 10);
let cursor = buf.readUInt32LE(eocd + 16);
const names = [];

for (let i = 0; i < total; i++) {
  if (buf.readUInt32LE(cursor) !== 0x02014b50) {
    console.error("bad central directory at entry " + i);
    process.exit(1);
  }
  const nameLen = buf.readUInt16LE(cursor + 28);
  const extraLen = buf.readUInt16LE(cursor + 30);
  const commentLen = buf.readUInt16LE(cursor + 32);
  names.push(buf.slice(cursor + 46, cursor + 46 + nameLen).toString("utf8").replace(/\\/g, "/"));
  cursor += 46 + nameLen + extraLen + commentLen;
}

const required = [
  FOLDER + "/index.html",
  FOLDER + "/serve.js",
  FOLDER + "/package.json",
  FOLDER + "/README.md",
  FOLDER + "/SECURITY.md",
  FOLDER + "/START-HERE.txt",
  FOLDER + "/assets/style.css",
  FOLDER + "/assets/app.js",
  FOLDER + "/assets/data.js",
  FOLDER + "/automation/build-docs.js",
  FOLDER + "/automation/build-full-package.js",
  FOLDER + "/automation/check-site.js",
  FOLDER + "/downloads/Abhijeet-Kumar-Prajapati-CV.pdf",
  FOLDER + "/downloads/Abhijeet-Kumar-Prajapati-Resume.pdf",
];

const missing = required.filter((r) => names.indexOf(r) === -1);

console.log("zip written : " + path.basename(ZIP));
console.log("files staged: " + copied);
console.log("entries     : " + total);
console.log("size        : " + (buf.length / 1024).toFixed(1) + " KB");
console.log("");
console.log("contents:");
names
  .filter((n) => n.indexOf("/") !== -1 && n.split("/").length <= 4)
  .forEach((n) => console.log("   " + n.replace(FOLDER + "/", "")));

if (missing.length) {
  console.error("\nMISSING FROM ARCHIVE:\n  " + missing.join("\n  "));
  process.exit(1);
}

console.log("\nall required files present");
console.log("staging removed, repository stays clean");